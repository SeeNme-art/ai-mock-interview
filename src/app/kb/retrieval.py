"""Offline FAISS build and candidate ranking against the approved SQLite bank."""
from __future__ import annotations

from hashlib import sha256 as hash_bytes
import json
import os
from pathlib import Path
import re
from typing import Iterable, Protocol, Sequence
from uuid import uuid4

import faiss
import numpy as np

from .seed import Difficulty, Dimension
from .store import canonical_json, list_questions, read_bank, read_questions, sha256

QUERY_VERSION = "objective-jd-skills-v1"


class Embedder(Protocol):
    model_id: str
    dimension: int

    def embed(self, texts: Sequence[str]) -> Iterable[np.ndarray]: ...


class IndexUnavailable(ValueError):
    """The caller must prompt for a rebuild or use explicitly unranked candidates."""


def document_text(question: dict) -> str:
    points = "；".join(question["answer_points"][:3])
    return f"题干：{question['content']}\n考察点：{question['objective']}\n要点：{points}"


def query_text(objective: str, jd: str, skills: Sequence[str]) -> str:
    if not objective.strip():
        raise ValueError("考察点不能为空")
    parts = [f"考察点：{objective.strip()}"]
    if jd.strip():
        parts.append(f"岗位要求：{jd.strip()}")
    clean_skills = [skill.strip() for skill in skills if skill.strip()]
    if clean_skills:
        parts.append("相关技能：" + "、".join(clean_skills))
    return "\n".join(parts)


def _unit_vectors(embedder: Embedder, texts: Sequence[str]) -> np.ndarray:
    vectors = np.array(list(embedder.embed(texts)), dtype=np.float32)
    if vectors.shape != (len(texts), embedder.dimension) or not np.isfinite(vectors).all():
        raise ValueError("向量数量、维度或数值不符合索引要求")
    norms = np.linalg.norm(vectors, axis=1)
    if not np.isfinite(norms).all() or (norms == 0).any():
        raise ValueError("向量无法归一化")
    faiss.normalize_L2(vectors)
    return vectors


def _metadata(questions: list[dict], embedder: Embedder) -> dict:
    return {
        "format": 1,
        "embedding_model": embedder.model_id,
        "dimension": embedder.dimension,
        "metric": "l2-normalized-inner-product",
        "query_version": QUERY_VERSION,
        "questions": [
            {
                "id": question["id"],
                "faiss_id": question["stable_faiss_id"],
                "revision": question["revision"],
                "content_hash": question["content_hash"],
                "embedding_input_hash": sha256(document_text(question)),
            }
            for question in questions
        ],
    }


def _read_generation(directory: Path, metadata: dict) -> faiss.IndexIDMap2:
    try:
        manifest = json.loads((directory / "manifest.json").read_text(encoding="utf-8"))
        if not isinstance(manifest, dict) or manifest.get("index_version") != directory.name:
            raise IndexUnavailable("索引清单的版本无效")
        checksum = manifest.pop("index_sha256", None)
        manifest.pop("index_version")
        if manifest != metadata:
            raise IndexUnavailable("索引与当前审核题库或向量配置不一致，请重建")
        payload = (directory / "questions.faiss").read_bytes()
        if hash_bytes(payload).hexdigest() != checksum:
            raise IndexUnavailable("索引文件校验失败，请重建")
        # Only deserialize bytes generated by this project's local rebuild command.
        index = faiss.deserialize_index(np.frombuffer(payload, dtype=np.uint8))
    except (OSError, UnicodeError, json.JSONDecodeError, RuntimeError) as exc:
        raise IndexUnavailable("本地索引缺失或无法加载，请重建") from exc
    ids = [entry["faiss_id"] for entry in metadata["questions"]]
    if (not isinstance(index, faiss.IndexIDMap2) or index.d != metadata["dimension"]
            or index.metric_type != faiss.METRIC_INNER_PRODUCT or index.ntotal != len(ids)
            or faiss.vector_to_array(index.id_map).tolist() != ids):
        raise IndexUnavailable("索引的 ID、向量数量、维度或距离配置不匹配，请重建")
    return index


def rebuild_index(db_path: Path, index_path: Path, embedder: Embedder) -> dict:
    questions = list_questions(db_path)
    if not questions:
        raise ValueError("题库没有审核通过的题目，无法建立索引")
    metadata = _metadata(questions, embedder)
    vectors = _unit_vectors(embedder, [document_text(question) for question in questions])
    ids = np.array([question["stable_faiss_id"] for question in questions], dtype=np.int64)
    index = faiss.IndexIDMap2(faiss.IndexFlatIP(embedder.dimension))
    index.add_with_ids(vectors, ids)
    version = uuid4().hex
    directory = index_path / version
    directory.mkdir(parents=True)
    payload = faiss.serialize_index(index).tobytes()
    manifest = {**metadata, "index_version": version, "index_sha256": hash_bytes(payload).hexdigest()}
    (directory / "questions.faiss").write_bytes(payload)
    (directory / "manifest.json").write_text(canonical_json(manifest), encoding="utf-8")
    _read_generation(directory, metadata)
    if _metadata(list_questions(db_path), embedder) != metadata:
        raise IndexUnavailable("重建期间审核题库发生变化，请停止导入后重试")
    pointer = index_path / f".{version}.tmp"
    try:
        pointer.write_text(version, encoding="ascii")
        os.replace(pointer, index_path / "current")
    finally:
        pointer.unlink(missing_ok=True)
    return manifest


def search_questions(db_path: Path, index_path: Path, embedder: Embedder, *, objective: str,
                     dimension: Dimension, difficulty: Difficulty, jd: str = "",
                     skills: Sequence[str] = (), exclude_ids: Sequence[str] = (), top_k: int = 3) -> list[dict]:
    if top_k < 1:
        raise ValueError("top_k 必须为正整数")
    text = query_text(objective, jd, skills)
    with read_bank(db_path) as db:
        eligible = read_questions(db, dimension=dimension, difficulty=difficulty, exclude_ids=exclude_ids)
        if not eligible:
            return []
        metadata = _metadata(read_questions(db), embedder)
    try:
        version = (index_path / "current").read_text(encoding="ascii")
    except (OSError, UnicodeError) as exc:
        raise IndexUnavailable("没有可用的本地索引，请先重建") from exc
    if re.fullmatch(r"[0-9a-f]{32}", version) is None:
        raise IndexUnavailable("索引版本指针无效，请重建")
    index = _read_generation(index_path / version, metadata)
    query = _unit_vectors(embedder, [text])
    # Search the entire small public index before applying the SQL candidate set.
    scores, ids = index.search(query, index.ntotal)
    by_id = {question["stable_faiss_id"]: question for question in eligible}
    ranked = sorted(((float(score), int(key)) for score, key in zip(scores[0], ids[0]) if key in by_id),
                    key=lambda item: (-item[0], item[1]))
    return [
        {"question": by_id[key], "score": score, "index_version": version, "query_version": QUERY_VERSION}
        for score, key in ranked[:top_k]
    ]
